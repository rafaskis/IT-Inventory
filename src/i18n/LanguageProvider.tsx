type LanguageContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: string, values?: Record<string, string | number>) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>('el')

  useEffect(() => { document.documentElement.lang = language }, [language])

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (key, values = {}) => {
      const translated = language === 'el' ? (greek[key] ?? key) : key
      return translated.replace(/{(\w+)}/g, (_, name: string) =>
        String(values[name] ?? `{${name}}`)
      )
    },
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider')
  return context
}

export function formatNumber(value: number, language: Language, options?: Intl.NumberFormatOptions) {
  return new Intl.NumberFormat(language === 'el' ? 'el-CY' : 'en-GB', options).format(value)
}

export function formatCurrency(value: number, language: Language, currency = 'EUR') {
  return new Intl.NumberFormat(language === 'el' ? 'el-CY' : 'en-GB', { style: 'currency', currency }).format(value)
}

export function formatDate(value: string | Date, language: Language) {
  const date = typeof value === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value)
    ? new Date(Date.UTC(Number(value.slice(0, 4)), Number(value.slice(5, 7)) - 1, Number(value.slice(8, 10))))
    : new Date(value)
  return new Intl.DateTimeFormat(language === 'el' ? 'el-CY' : 'en-GB', {
    day: '2-digit', month: '2-digit', year: 'numeric', timeZone: /^\d{4}-\d{2}-\d{2}$/.test(String(value)) ? 'UTC' : 'Europe/Nicosia',
  }).format(date)
}

export function formatDateTime(value: string | Date, language: Language) {
  return new Intl.DateTimeFormat(language === 'el' ? 'el-CY' : 'en-GB', {
    day: '2-digit', month: '2-digit', year: 'numeric',
    hour: '2-digit', minute: '2-digit', hourCycle: 'h23', timeZone: 'Europe/Nicosia',
  }).format(new Date(value))
}

export function formatPercentage(value: number, language: Language, maximumFractionDigits = 1) {
  return new Intl.NumberFormat(language === 'el' ? 'el-CY' : 'en-GB', { style: 'percent', maximumFractionDigits }).format(value)
}

export function formatPdfDate(value: string | Date) {
  const dateOnly = typeof value === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value)
  const date = dateOnly ? new Date(`${value}T00:00:00Z`) : new Date(value)
  return new Intl.DateTimeFormat('en-GB', { day: '2-digit', month: '2-digit', year: 'numeric', timeZone: dateOnly ? 'UTC' : 'Europe/Nicosia' }).format(date)
}

export function formatPdfDateTime(value: string | Date) {
  return new Intl.DateTimeFormat('en-GB', { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit', hourCycle: 'h23', timeZone: 'Europe/Nicosia' }).format(new Date(value))
}

export function formatPdfNumber(value: number, maximumFractionDigits = 2) {
  return new Intl.NumberFormat('en-US', { useGrouping: true, maximumFractionDigits }).format(value)
}
