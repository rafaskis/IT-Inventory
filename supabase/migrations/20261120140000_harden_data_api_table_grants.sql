-- IT-Inventory security hardening
-- Browser clients only need read access to application tables.
-- All writes are performed by authenticated Edge Functions / privileged database functions.
-- RLS remains enabled and continues to determine which authenticated rows are visible.

DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'profiles',
    'employees',
    'locations',
    'item_types',
    'brands',
    'models',
    'inventory_items',
    'inventory_item_employees',
    'audit_events'
  ]
  LOOP
    EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM anon', table_name);
    EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM authenticated', table_name);
    EXECUTE format('GRANT SELECT ON TABLE public.%I TO authenticated', table_name);
  END LOOP;
END
$$;

-- No browser-side inserts use table sequences; IDs are generated by the database
-- and writes are routed through privileged server-side operations.
REVOKE ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;

-- Ensure future tables created by the migration owner do not accidentally inherit
-- broad browser write permissions. SELECT must be granted explicitly when needed.
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  REVOKE ALL PRIVILEGES ON TABLES FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  REVOKE ALL PRIVILEGES ON SEQUENCES FROM anon, authenticated;
