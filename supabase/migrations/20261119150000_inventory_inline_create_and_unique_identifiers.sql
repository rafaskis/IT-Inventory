-- Inventory inline creation, optional serial numbers, and scoped identifier uniqueness.
ALTER TABLE public.inventory_items ALTER COLUMN serial_number DROP NOT NULL;

CREATE OR REPLACE FUNCTION public.inventory_create_item(
    p_item JSONB,
    p_employee_ids BIGINT[],
    p_actor_id UUID,
    p_actor_username TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_id BIGINT;
    v_item_code TEXT;
    v_employee_id BIGINT;
    v_employee_ids BIGINT[];
BEGIN
    -- Verify the actor.
    IF NOT EXISTS (
        SELECT 1
        FROM public.profiles
        WHERE id = p_actor_id
          AND username = p_actor_username
          AND is_active = TRUE
          AND role IN ('administrator', 'inventory_manager')
    ) THEN
        RAISE EXCEPTION 'Inventory management access required.';
    END IF;

    -- Validate the request.
    IF p_item IS NULL OR pg_catalog.jsonb_typeof(p_item) <> 'object' THEN
        RAISE EXCEPTION 'Invalid inventory item data.';
    END IF;


    IF NULLIF(p_item->>'item_type_id', '') IS NULL
       OR NULLIF(p_item->>'brand_id', '') IS NULL
       OR NULLIF(p_item->>'model_id', '') IS NULL
       OR NULLIF(p_item->>'location_id', '') IS NULL THEN
        RAISE EXCEPTION 'Item type, brand, model and location are required.';
    END IF;

    -- Normalize employee IDs.
SELECT COALESCE(
    pg_catalog.array_agg(DISTINCT u.employee_id),
    ARRAY[]::BIGINT[]
)
INTO v_employee_ids
FROM pg_catalog.unnest(
    COALESCE(p_employee_ids, ARRAY[]::BIGINT[])
) AS u(employee_id);

    -- Ensure all selected employees exist.
    IF pg_catalog.cardinality(v_employee_ids) > 0
       AND (
           SELECT COUNT(*)
           FROM public.employees
           WHERE id = ANY(v_employee_ids)
       ) <> pg_catalog.cardinality(v_employee_ids) THEN
        RAISE EXCEPTION 'One or more selected employees do not exist.';
    END IF;

    -- Create the inventory item.
    -- item_code is generated by the database trigger.
    INSERT INTO public.inventory_items (
        item_type_id,
        brand_id,
        model_id,
        serial_number,
        mac_address,
        pc_name,
        ip_address,
        socket,
        location_id,
        notes,
        document_number,
        invoice,
        purchase_date,
        warranty_until,
        store,
        created_by,
        updated_by
    )
    VALUES (
        (p_item->>'item_type_id')::BIGINT,
        (p_item->>'brand_id')::BIGINT,
        (p_item->>'model_id')::BIGINT,
        NULLIF(pg_catalog.btrim(p_item->>'serial_number'), ''),
        NULLIF(pg_catalog.btrim(p_item->>'mac_address'), ''),
        NULLIF(pg_catalog.btrim(p_item->>'pc_name'), ''),
        NULLIF(pg_catalog.btrim(p_item->>'ip_address'), ''),
        NULLIF(pg_catalog.btrim(p_item->>'socket'), ''),
        (p_item->>'location_id')::BIGINT,
        NULLIF(pg_catalog.btrim(p_item->>'notes'), ''),
        NULLIF(p_item->>'document_number', '')::INTEGER,
        NULLIF(pg_catalog.btrim(p_item->>'invoice'), ''),
        NULLIF(p_item->>'purchase_date', '')::DATE,
        NULLIF(p_item->>'warranty_until', '')::DATE,
        NULLIF(pg_catalog.btrim(p_item->>'store'), ''),
        p_actor_id,
        p_actor_id
    )
    RETURNING id, item_code
    INTO v_id, v_item_code;

    -- Create employee assignments.
    FOREACH v_employee_id IN ARRAY v_employee_ids
    LOOP
        INSERT INTO public.inventory_item_employees (
            inventory_item_id,
            employee_id
        )
        VALUES (v_id, v_employee_id);

        INSERT INTO public.audit_events (
            entity_type,
            entity_id,
            action,
            actor_user_id,
            actor_username,
            changes,
            details
        )
        SELECT
            'inventory_item',
            v_id::TEXT,
            'employee_assigned',
            p_actor_id,
            p_actor_username,
            pg_catalog.jsonb_build_object(
                'employee',
                pg_catalog.jsonb_build_object(
                    'old', NULL,
                    'new', e.full_name
                )
            ),
            pg_catalog.jsonb_build_object(
                'item_code', v_item_code,
                'employee_id', e.id
            )
        FROM public.employees e
        WHERE e.id = v_employee_id;
    END LOOP;

    -- Record item creation.
    INSERT INTO public.audit_events (
        entity_type,
        entity_id,
        action,
        actor_user_id,
        actor_username,
        changes,
        details
    )

    VALUES (
        'inventory_item',
        v_id::TEXT,
        'inventory_item_created',
        p_actor_id,
        p_actor_username,
        pg_catalog.jsonb_build_object(
            'item',
            pg_catalog.jsonb_build_object(
                'old', NULL,
                'new', (
                    SELECT pg_catalog.jsonb_build_object(
                        'item_code', i.item_code,
                        'item_type', it.name,
                        'brand', b.name,
                        'model', m.name,
                        'serial_number', i.serial_number,
                        'mac_address', i.mac_address,
                        'pc_name', i.pc_name,
                        'ip_address', i.ip_address,
                        'socket', i.socket,
                        'location', l.name,
                        'notes', i.notes,
                        'document_number', i.document_number,
                        'invoice', i.invoice,
                        'purchase_date', i.purchase_date,
                        'warranty_until', i.warranty_until,
                        'store', i.store
                    )
                    FROM public.inventory_items i
                    JOIN public.item_types it ON it.id = i.item_type_id
                    JOIN public.brands b ON b.id = i.brand_id
                    JOIN public.models m ON m.id = i.model_id
                    JOIN public.locations l ON l.id = i.location_id
                    WHERE i.id = v_id
                )
            )
        ),
        pg_catalog.jsonb_build_object(
            'item_code', v_item_code,
            'employee_ids', v_employee_ids
        )
    );


    RETURN pg_catalog.jsonb_build_object(
        'success', TRUE,
        'id', v_id,
        'item_code', v_item_code
    );
END;
$function$;

CREATE OR REPLACE FUNCTION public.inventory_update_item(
    p_id BIGINT,
    p_item JSONB,
    p_employee_ids BIGINT[],
    p_actor_id UUID,
    p_actor_username TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_old public.inventory_items%ROWTYPE;
    v_new public.inventory_items%ROWTYPE;
    v_old_json JSONB;
    v_new_json JSONB;
    v_changes JSONB := '{}'::JSONB;
    v_employee_id BIGINT;
    v_employee_ids BIGINT[];
    v_employee_name TEXT;
    v_assignments_changed BOOLEAN := FALSE;
BEGIN
    -- Verify actor.
    IF NOT EXISTS (
        SELECT 1
        FROM public.profiles
        WHERE id = p_actor_id
          AND username = p_actor_username
          AND is_active = TRUE
          AND role IN ('administrator', 'inventory_manager')
    ) THEN
        RAISE EXCEPTION 'Inventory management access required.';
    END IF;

    IF p_id IS NULL OR p_id <= 0 THEN
        RAISE EXCEPTION 'A valid inventory item ID is required.';
    END IF;

    IF p_item IS NULL OR pg_catalog.jsonb_typeof(p_item) <> 'object' THEN
        RAISE EXCEPTION 'Invalid inventory item data.';
    END IF;

    -- Only editable fields are accepted.
    IF EXISTS (
        SELECT 1
        FROM pg_catalog.jsonb_object_keys(p_item) AS k(key)
        WHERE key NOT IN (
            'item_type_id',
            'brand_id',
            'model_id',
            'serial_number',
            'mac_address',
            'pc_name',
            'ip_address',
            'socket',
            'location_id',
            'notes',
            'document_number',
            'invoice',
            'purchase_date',
            'warranty_until',
            'store'
        )
    ) THEN
        RAISE EXCEPTION 'The request contains unsupported inventory fields.';
    END IF;

    -- Lock the item during the transaction.
    SELECT *
    INTO v_old
    FROM public.inventory_items
    WHERE id = p_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Inventory item not found.';
    END IF;

    -- Validate required fields after applying the requested changes.
    IF (
        CASE WHEN p_item ? 'item_type_id'
            THEN NULLIF(p_item->>'item_type_id', '')::BIGINT
            ELSE v_old.item_type_id
        END
    ) IS NULL
    OR (
        CASE WHEN p_item ? 'brand_id'
            THEN NULLIF(p_item->>'brand_id', '')::BIGINT
            ELSE v_old.brand_id
        END
    ) IS NULL
    OR (
        CASE WHEN p_item ? 'model_id'
            THEN NULLIF(p_item->>'model_id', '')::BIGINT
            ELSE v_old.model_id
        END
    ) IS NULL
    OR (
        CASE WHEN p_item ? 'location_id'
            THEN NULLIF(p_item->>'location_id', '')::BIGINT
            ELSE v_old.location_id
        END
    ) IS NULL
    THEN
        RAISE EXCEPTION 'Item type, brand, model and location are required.';
    END IF;

    -- Normalize employee IDs only when assignments were supplied.
    IF p_employee_ids IS NOT NULL THEN

        SELECT COALESCE(
            pg_catalog.array_agg(DISTINCT u.employee_id),
            ARRAY[]::BIGINT[]
        )
        INTO v_employee_ids
        FROM pg_catalog.unnest(p_employee_ids) AS u(employee_id);

        IF pg_catalog.cardinality(v_employee_ids) > 0
           AND (
               SELECT COUNT(*)
               FROM public.employees
               WHERE id = ANY(v_employee_ids)
           ) <> pg_catalog.cardinality(v_employee_ids) THEN
            RAISE EXCEPTION 'One or more selected employees do not exist.';
        END IF;
    END IF;

    -- Apply requested item changes.
    UPDATE public.inventory_items
    SET
        item_type_id = CASE
            WHEN p_item ? 'item_type_id'
            THEN (p_item->>'item_type_id')::BIGINT
            ELSE item_type_id
        END,
        brand_id = CASE
            WHEN p_item ? 'brand_id'
            THEN (p_item->>'brand_id')::BIGINT
            ELSE brand_id
        END,
        model_id = CASE
            WHEN p_item ? 'model_id'
            THEN (p_item->>'model_id')::BIGINT
            ELSE model_id
        END,
        serial_number = CASE
            WHEN p_item ? 'serial_number'
            THEN NULLIF(pg_catalog.btrim(p_item->>'serial_number'), '')
            ELSE serial_number
        END,
        mac_address = CASE
            WHEN p_item ? 'mac_address'
            THEN NULLIF(pg_catalog.btrim(p_item->>'mac_address'), '')
            ELSE mac_address
        END,
        pc_name = CASE
            WHEN p_item ? 'pc_name'
            THEN NULLIF(pg_catalog.btrim(p_item->>'pc_name'), '')
            ELSE pc_name
        END,
        ip_address = CASE
            WHEN p_item ? 'ip_address'
            THEN NULLIF(pg_catalog.btrim(p_item->>'ip_address'), '')
            ELSE ip_address
        END,
        socket = CASE
            WHEN p_item ? 'socket'
            THEN NULLIF(pg_catalog.btrim(p_item->>'socket'), '')
            ELSE socket
        END,
        location_id = CASE
            WHEN p_item ? 'location_id'
            THEN (p_item->>'location_id')::BIGINT
            ELSE location_id
        END,
        notes = CASE
            WHEN p_item ? 'notes'
            THEN NULLIF(pg_catalog.btrim(p_item->>'notes'), '')
            ELSE notes
        END,
        document_number = CASE
            WHEN p_item ? 'document_number'
            THEN NULLIF(p_item->>'document_number', '')::INTEGER
            ELSE document_number
        END,
        invoice = CASE
            WHEN p_item ? 'invoice'
            THEN NULLIF(pg_catalog.btrim(p_item->>'invoice'), '')
            ELSE invoice
        END,
        purchase_date = CASE
            WHEN p_item ? 'purchase_date'
            THEN NULLIF(p_item->>'purchase_date', '')::DATE
            ELSE purchase_date
        END,
        warranty_until = CASE
            WHEN p_item ? 'warranty_until'
            THEN NULLIF(p_item->>'warranty_until', '')::DATE
            ELSE warranty_until
        END,
        store = CASE
            WHEN p_item ? 'store'
            THEN NULLIF(pg_catalog.btrim(p_item->>'store'), '')
            ELSE store
        END
    WHERE id = p_id
    RETURNING * INTO v_new;


    -- Build readable snapshots using catalogue names.
    v_old_json := (
        SELECT pg_catalog.jsonb_build_object(
            'item_type', it.name,
            'brand', b.name,
            'model', m.name,
            'serial_number', v_old.serial_number,
            'mac_address', v_old.mac_address,
            'pc_name', v_old.pc_name,
            'ip_address', v_old.ip_address,
            'socket', v_old.socket,
            'location', l.name,
            'notes', v_old.notes,
            'document_number', v_old.document_number,
            'invoice', v_old.invoice,
            'purchase_date', v_old.purchase_date,
            'warranty_until', v_old.warranty_until,
            'store', v_old.store
        )
        FROM public.item_types it
        JOIN public.brands b ON b.id = v_old.brand_id
        JOIN public.models m ON m.id = v_old.model_id
        JOIN public.locations l ON l.id = v_old.location_id
        WHERE it.id = v_old.item_type_id
    );

    v_new_json := (
        SELECT pg_catalog.jsonb_build_object(
            'item_type', it.name,
            'brand', b.name,
            'model', m.name,
            'serial_number', v_new.serial_number,
            'mac_address', v_new.mac_address,
            'pc_name', v_new.pc_name,
            'ip_address', v_new.ip_address,
            'socket', v_new.socket,
            'location', l.name,
            'notes', v_new.notes,
            'document_number', v_new.document_number,
            'invoice', v_new.invoice,
            'purchase_date', v_new.purchase_date,
            'warranty_until', v_new.warranty_until,
            'store', v_new.store
        )
        FROM public.item_types it
        JOIN public.brands b ON b.id = v_new.brand_id
        JOIN public.models m ON m.id = v_new.model_id
        JOIN public.locations l ON l.id = v_new.location_id
        WHERE it.id = v_new.item_type_id
    );

    -- Record only fields whose displayed values actually changed.
    SELECT COALESCE(
        pg_catalog.jsonb_object_agg(
            field.key,
            pg_catalog.jsonb_build_object(
                'old', field.value,
                'new', v_new_json->field.key
            )
        ),
        '{}'::JSONB
    )
    INTO v_changes
    FROM pg_catalog.jsonb_each(v_old_json) AS field
    WHERE field.value IS DISTINCT FROM v_new_json->field.key;


    -- Replace employee assignments only when supplied.
    IF p_employee_ids IS NOT NULL THEN

        -- Remove assignments no longer selected.
        FOR v_employee_id, v_employee_name IN
            SELECT e.id, e.full_name
            FROM public.inventory_item_employees a
            JOIN public.employees e ON e.id = a.employee_id
            WHERE a.inventory_item_id = p_id
              AND NOT (e.id = ANY(v_employee_ids))
            FOR UPDATE OF a
        LOOP
            DELETE FROM public.inventory_item_employees
            WHERE inventory_item_id = p_id
              AND employee_id = v_employee_id;

            INSERT INTO public.audit_events (
                entity_type,
                entity_id,
                action,
                actor_user_id,
                actor_username,
                changes,
                details
            )
            VALUES (
                'inventory_item',
                p_id::TEXT,
                'employee_unassigned',
                p_actor_id,
                p_actor_username,
                pg_catalog.jsonb_build_object(
                    'employee',
                    pg_catalog.jsonb_build_object(
                        'old', v_employee_name,
                        'new', NULL
                    )
                ),
                pg_catalog.jsonb_build_object(
                    'item_code', v_new.item_code,
                    'employee_id', v_employee_id
                )
            );

            v_assignments_changed := TRUE;
        END LOOP;

        -- Add newly selected employees.
        FOR v_employee_id, v_employee_name IN
            SELECT e.id, e.full_name
            FROM public.employees e
            WHERE e.id = ANY(v_employee_ids)
              AND NOT EXISTS (
                  SELECT 1
                  FROM public.inventory_item_employees a
                  WHERE a.inventory_item_id = p_id
                    AND a.employee_id = e.id
              )
            FOR UPDATE OF e
        LOOP
            INSERT INTO public.inventory_item_employees (
                inventory_item_id,
                employee_id
            )
            VALUES (p_id, v_employee_id);

            INSERT INTO public.audit_events (
                entity_type,
                entity_id,
                action,
                actor_user_id,
                actor_username,
                changes,
                details
            )
            VALUES (
                'inventory_item',
                p_id::TEXT,
                'employee_assigned',
                p_actor_id,
                p_actor_username,
                pg_catalog.jsonb_build_object(
                    'employee',
                    pg_catalog.jsonb_build_object(
                        'old', NULL,
                        'new', v_employee_name
                    )
                ),
                pg_catalog.jsonb_build_object(
                    'item_code', v_new.item_code,
                    'employee_id', v_employee_id
                )
            );

            v_assignments_changed := TRUE;
        END LOOP;
    END IF;

    -- Update modification metadata only when something changed.
    IF v_changes <> '{}'::JSONB OR v_assignments_changed THEN

        UPDATE public.inventory_items
        SET
            updated_by = p_actor_id,
            updated_at = pg_catalog.now()
        WHERE id = p_id;

        IF v_changes <> '{}'::JSONB THEN
            INSERT INTO public.audit_events (
                entity_type,
                entity_id,
                action,
                actor_user_id,
                actor_username,
                changes,
                details
            )
            VALUES (
                'inventory_item',
                p_id::TEXT,
                'inventory_item_updated',
                p_actor_id,
                p_actor_username,
                v_changes,
                pg_catalog.jsonb_build_object(
                    'item_code', v_new.item_code
                )
            );
        END IF;
    END IF;

    RETURN pg_catalog.jsonb_build_object(
        'success', TRUE,
        'id', p_id,
        'item_code', v_new.item_code,
        'changes', v_changes,
        'assignments_changed', v_assignments_changed
    );
END;
$function$;

-- Enforce S/N and MAC uniqueness within the same type + brand + model.
-- Transaction-scoped advisory locks serialize concurrent inserts/updates for the same value.
CREATE OR REPLACE FUNCTION public.enforce_inventory_identifier_uniqueness()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_serial TEXT := NULLIF(pg_catalog.lower(pg_catalog.btrim(NEW.serial_number)), '');
    v_mac TEXT := NULLIF(pg_catalog.lower(pg_catalog.btrim(NEW.mac_address)), '');
    v_key TEXT;
    v_keys TEXT[] := ARRAY[]::TEXT[];
BEGIN
    IF v_serial IS NOT NULL THEN
        v_keys := pg_catalog.array_append(v_keys,
            'serial|' || NEW.item_type_id::TEXT || '|' || NEW.brand_id::TEXT || '|' || NEW.model_id::TEXT || '|' || v_serial);
    END IF;
    IF v_mac IS NOT NULL THEN
        v_keys := pg_catalog.array_append(v_keys,
            'mac|' || NEW.item_type_id::TEXT || '|' || NEW.brand_id::TEXT || '|' || NEW.model_id::TEXT || '|' || v_mac);
    END IF;

    FOR v_key IN SELECT x FROM pg_catalog.unnest(v_keys) AS t(x) ORDER BY x LOOP
        PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_key, 0));
    END LOOP;

    IF v_serial IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.inventory_items i
        WHERE i.item_type_id = NEW.item_type_id
          AND i.brand_id = NEW.brand_id
          AND i.model_id = NEW.model_id
          AND pg_catalog.lower(pg_catalog.btrim(i.serial_number)) = v_serial
          AND (TG_OP = 'INSERT' OR i.id <> NEW.id)
    ) THEN
        RAISE EXCEPTION 'This S/N is already used by another item with the same Item Type, Brand and Model.';
    END IF;

    IF v_mac IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.inventory_items i
        WHERE i.item_type_id = NEW.item_type_id
          AND i.brand_id = NEW.brand_id
          AND i.model_id = NEW.model_id
          AND pg_catalog.lower(pg_catalog.btrim(i.mac_address)) = v_mac
          AND (TG_OP = 'INSERT' OR i.id <> NEW.id)
    ) THEN
        RAISE EXCEPTION 'This MAC address is already used by another item with the same Item Type, Brand and Model.';
    END IF;
    RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS inventory_identifier_uniqueness ON public.inventory_items;
CREATE TRIGGER inventory_identifier_uniqueness
BEFORE INSERT OR UPDATE OF item_type_id, brand_id, model_id, serial_number, mac_address
ON public.inventory_items
FOR EACH ROW EXECUTE FUNCTION public.enforce_inventory_identifier_uniqueness();
REVOKE ALL ON FUNCTION public.enforce_inventory_identifier_uniqueness() FROM PUBLIC, anon, authenticated;

-- Single transaction for optional catalogue, employee and location creation plus item creation.
CREATE OR REPLACE FUNCTION public.inventory_create_item_with_related(
    p_item JSONB,
    p_employee_ids BIGINT[],
    p_new_employee_names TEXT[],
    p_new_item_type_name TEXT,
    p_new_brand_name TEXT,
    p_new_model_name TEXT,
    p_new_location_name TEXT,
    p_actor_id UUID,
    p_actor_username TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_item JSONB := p_item;
    v_type_id BIGINT;
    v_brand_id BIGINT;
    v_model_id BIGINT;
    v_location_id BIGINT;
    v_employee_ids BIGINT[] := COALESCE(p_employee_ids, ARRAY[]::BIGINT[]);
    v_name TEXT;
    v_employee_id BIGINT;
    v_result JSONB;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = p_actor_id AND username = p_actor_username
          AND is_active = TRUE AND role IN ('administrator', 'inventory_manager')
    ) THEN RAISE EXCEPTION 'Inventory management access required.'; END IF;
    IF p_item IS NULL OR pg_catalog.jsonb_typeof(p_item) <> 'object' THEN
        RAISE EXCEPTION 'Invalid inventory item data.';
    END IF;

    -- Resolve/create item type.
    IF NULLIF(pg_catalog.btrim(p_new_item_type_name), '') IS NOT NULL THEN
        v_result := public.catalogue_create_entry('item_type', p_new_item_type_name, NULL, NULL, p_actor_id, p_actor_username);
        v_type_id := (v_result->>'id')::BIGINT;
    ELSE
        v_type_id := NULLIF(v_item->>'item_type_id', '')::BIGINT;
    END IF;
    IF v_type_id IS NULL OR NOT EXISTS (SELECT 1 FROM public.item_types WHERE id = v_type_id) THEN
        RAISE EXCEPTION 'Select an Item Type or enter a new Item Type name.';
    END IF;

    -- Resolve/create brand under the resolved type.
    IF NULLIF(pg_catalog.btrim(p_new_brand_name), '') IS NOT NULL THEN
        v_result := public.catalogue_create_entry('brand', p_new_brand_name, v_type_id, NULL, p_actor_id, p_actor_username);
        v_brand_id := (v_result->>'id')::BIGINT;
    ELSE
        v_brand_id := NULLIF(v_item->>'brand_id', '')::BIGINT;
    END IF;
    IF v_brand_id IS NULL OR NOT EXISTS (
        SELECT 1 FROM public.brands WHERE id = v_brand_id AND item_type_id = v_type_id
    ) THEN RAISE EXCEPTION 'Select a Brand or enter a new Brand name.'; END IF;

    -- Resolve/create model under the resolved brand.
    IF NULLIF(pg_catalog.btrim(p_new_model_name), '') IS NOT NULL THEN
        v_result := public.catalogue_create_entry('model', p_new_model_name, v_type_id, v_brand_id, p_actor_id, p_actor_username);
        v_model_id := (v_result->>'id')::BIGINT;
    ELSE
        v_model_id := NULLIF(v_item->>'model_id', '')::BIGINT;
    END IF;
    IF v_model_id IS NULL OR NOT EXISTS (
        SELECT 1 FROM public.models WHERE id = v_model_id AND brand_id = v_brand_id AND item_type_id = v_type_id
    ) THEN RAISE EXCEPTION 'Select a Model or enter a new Model name.'; END IF;

    -- Resolve/create location (new locations intentionally have no notes).
    IF NULLIF(pg_catalog.btrim(p_new_location_name), '') IS NOT NULL THEN
        v_name := pg_catalog.btrim(p_new_location_name);
        IF pg_catalog.length(v_name) > 100 THEN RAISE EXCEPTION 'Location name cannot exceed 100 characters.'; END IF;
        INSERT INTO public.locations(name, notes) VALUES (v_name, NULL) RETURNING id INTO v_location_id;
        INSERT INTO public.audit_events(entity_type, entity_id, action, actor_user_id, actor_username, changes, details)
        VALUES ('location', v_location_id::TEXT, 'location_created', p_actor_id, p_actor_username,
            pg_catalog.jsonb_build_object('name', pg_catalog.jsonb_build_object('old', NULL, 'new', v_name)),
            pg_catalog.jsonb_build_object('source', 'inventory_create'));
    ELSE
        v_location_id := NULLIF(v_item->>'location_id', '')::BIGINT;
    END IF;
    IF v_location_id IS NULL OR NOT EXISTS (SELECT 1 FROM public.locations WHERE id = v_location_id) THEN
        RAISE EXCEPTION 'Select a Location or enter a new Location name.';
    END IF;

    -- Create any new employees. Each insert and audit is part of this transaction.
    IF pg_catalog.cardinality(COALESCE(p_new_employee_names, ARRAY[]::TEXT[])) > 50 THEN
        RAISE EXCEPTION 'You can add a maximum of 50 new employees at once.';
    END IF;
    FOREACH v_name IN ARRAY COALESCE(p_new_employee_names, ARRAY[]::TEXT[])
    LOOP
        v_name := pg_catalog.btrim(v_name);
        IF v_name = '' THEN CONTINUE; END IF;
        IF pg_catalog.length(v_name) > 150 THEN RAISE EXCEPTION 'Employee names cannot exceed 150 characters.'; END IF;
        INSERT INTO public.employees(full_name) VALUES (v_name) RETURNING id INTO v_employee_id;
        v_employee_ids := pg_catalog.array_append(v_employee_ids, v_employee_id);
        INSERT INTO public.audit_events(entity_type, entity_id, action, actor_user_id, actor_username, changes, details)
        VALUES ('employee', v_employee_id::TEXT, 'employee_created', p_actor_id, p_actor_username,
            pg_catalog.jsonb_build_object('full_name', pg_catalog.jsonb_build_object('old', NULL, 'new', v_name)),
            pg_catalog.jsonb_build_object('source', 'inventory_create'));
    END LOOP;

    v_item := v_item || pg_catalog.jsonb_build_object(
        'item_type_id', v_type_id, 'brand_id', v_brand_id,
        'model_id', v_model_id, 'location_id', v_location_id
    );
    SELECT COALESCE(pg_catalog.array_agg(DISTINCT x ORDER BY x), ARRAY[]::BIGINT[])
    INTO v_employee_ids FROM pg_catalog.unnest(v_employee_ids) AS t(x);

    v_result := public.inventory_create_item(v_item, v_employee_ids, p_actor_id, p_actor_username);
    RETURN v_result || pg_catalog.jsonb_build_object(
        'created_related', pg_catalog.jsonb_build_object(
            'item_type', NULLIF(pg_catalog.btrim(p_new_item_type_name), '') IS NOT NULL,
            'brand', NULLIF(pg_catalog.btrim(p_new_brand_name), '') IS NOT NULL,
            'model', NULLIF(pg_catalog.btrim(p_new_model_name), '') IS NOT NULL,
            'location', NULLIF(pg_catalog.btrim(p_new_location_name), '') IS NOT NULL,
            'employees', pg_catalog.cardinality(COALESCE(p_new_employee_names, ARRAY[]::TEXT[]))
        )
    );
END;
